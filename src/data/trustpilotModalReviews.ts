export function getTrustpilotModalReviews(language: LanguageCode): TrustpilotModalReviewItem[] {
  return RAW_TRUSTPILOT_SEEDS.map((seed, index) => {
    const count = seed.reviewsByAuthor ?? 1;
    const countLabel =
      language === 'en'
        ? count === 1
          ? '1 review'
          : `${count} reviews`
        : language === 'es'
          ? count === 1
            ? '1 opinión'
            : `${count} opiniones`
          : count === 1
            ? '1 avaliação'
            : `${count} avaliações`;

    return {
      id: index + 1,
      author: seed.author,
      avatarColor: AVATAR_PALETTE[index % AVATAR_PALETTE.length],
      location: `BR • ${countLabel}`,
      date: formatTrustpilotDaysAgo(seed.baseDays, language),
      experienceDate: formatTrustpilotExperienceDate(seed.baseDays, language),
      title:
        language === 'en' && seed.titleEn
          ? seed.titleEn
          : language === 'es' && seed.titleEs
            ? seed.titleEs
            : seed.title,
      comment:
        language === 'en' && seed.commentEn
          ? seed.commentEn
          : language === 'es' && seed.commentEs
            ? seed.commentEs
            : seed.comment,
      rating: seed.rating,
      baseHelpful: seed.baseHelpful ?? 0,
    };
  });
}
