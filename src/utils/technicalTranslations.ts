const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const patterns = terms.map(([pt,en,es]) => ({pattern: new RegExp(`(?<![\\p{L}])${escape(pt)}(?![\\p{L}])`, 'gu'), en, es}));
export function translateTechnicalText(value: string, language: LanguageCode): string {
  if (language !== 'en' && language !== 'es') return value;
  if (!/GB|GHz|DirectX|OpenGL|WINDOWS:|MAC:|Windows|macOS|Versão|Mensal|Anual|Assinatura|Todos os Módulos|Chave Original|V-Ray|sem sistema|Processador|Placa|Compatível|Espaço livre|3 Meses|6 Meses|12 Meses/.test(value)) return value;
  return patterns.reduce((text, term) => text.replace(term.pattern, term[language]), value);
}
